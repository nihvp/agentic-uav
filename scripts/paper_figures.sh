#!/usr/bin/env bash
# Copy example frames, the vision model's replies and the score summary into
# docs/figures/paper/ for docs/PAPER_RESULTS.md (run on the VM after scoring).
#   scripts/paper_figures.sh              scenes 1 (emergency) and 2 (normal)
#   scripts/paper_figures.sh 1 2 18       other scenes
# Then commit docs/figures/paper/ to share it (git add docs/figures/paper && git commit).
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=docs/figures/paper
SCENES=("$@"); [[ ${#SCENES[@]} -gt 0 ]] || SCENES=(1 2)
mkdir -p "$OUT"

for id in "${SCENES[@]}"; do
  src=$(printf "experiments/paper/captures/scene_%02d/rgb_0.png" "$id")
  cp "$src" "$(printf "%s/scene_%02d.png" "$OUT" "$id")"
done
cp experiments/paper/results/summary.md "$OUT/summary.md"

python3 - "$OUT" "${SCENES[@]}" <<'EOF'
import glob, json, sys
out, ids = sys.argv[1], [int(i) for i in sys.argv[2:]]
truth = {s["id"]: s for s in json.load(open("experiments/paper/scenes.json"))["scenes"]}
lines = ["# Example samples", "",
         "Each sample: the frame all systems saw, the ground truth (for scoring only), and",
         "each system's output. Generated by scripts/paper_figures.sh.", ""]
results = {}
for path in sorted(glob.glob("experiments/paper/results/*.jsonl"), key=lambda p: (not p.endswith("/rule.jsonl"), p)):
    name = path.rsplit("/", 1)[1][:-len(".jsonl")]
    results[name] = {r["scene_id"]: r for r in map(json.loads, filter(str.strip, open(path)))}
for i in ids:
    t = truth[i]
    lying = sum(p["posture"] == "lying" for p in t["people"])
    lines += [f"## Scene {i}: {t['label']}", "",
              f"![scene {i}](scene_{i:02d}.png)", "",
              f"Ground truth: {len(t['people'])} people ({lying} lying), label **{t['label']}**.", ""]
    for name, recs in results.items():
        r = recs.get(i)
        if not r:
            continue
        o = r["output"]
        head = f"**{name}**: {r['processing_time_s']:.3f} s, YOLO {len(r['yolo']['detections'])} persons"
        if "llm" in r:
            head += f", {r['llm'].get('completion_tokens')} tokens"
        lines += [head, "", "```json", json.dumps(o, indent=2), "```", ""]
open(f"{out}/examples.md", "w").write("\n".join(lines) + "\n")
print(f"wrote {out}/examples.md, {len(ids)} frames and summary.md")
EOF
